"""Research agent.

router -> answer                                                        (follow-up questions)
router -> planner -> 4 researchers (parallel) -> reviewer -> synthesizer
                                                    ^   |
                                                    |   v   (optional, guarded)
                                                 follow-ups: re-search notes/arXiv/GitHub/YouTube, or a Python check

Loop prevention, at two levels:
  researcher tool loop  - hard cap MAX_TOOL_CALLS; every call and result is hashed; a repeated call is
                          refused and a repeated result is flagged, the prompt is rewritten with the failed
                          attempts, and after MAX_REPEATS repeats the model must report without tools.
  reviewer cycle        - hard cap MAX_REVIEW_ROUNDS, MAX_FOLLOWUPS_PER_ROUND, MAX_FOLLOWUPS_PER_SOURCE;
                          (source, normalised query) hashes block repeats (cycle detection); a round that
                          brings no new raw results (by hash) ends the cycle, so state must keep changing.
Python checks run in Gemini's hosted code-execution sandbox (no network, no access to this machine);
nothing generated by a model is ever executed locally.
"""
import json
from collections import Counter
from typing import Annotated, Literal

from langchain_core.messages import AIMessage, HumanMessage, SystemMessage, ToolMessage
from langgraph.graph import END, START, MessagesState, StateGraph
from langgraph.graph.message import add_messages
from langgraph.types import Send
from pydantic import BaseModel, Field
from typing_extensions import TypedDict

from . import cache
from .config import MODEL
from .guards import action_key, call_key, digest, is_empty, outcome
from .llm import FAST_LLM, MAIN_LLM, RESEARCH_LLM, gemini, text_of
from .tools import arxiv_search, github_search, search_local_notes, youtube_search

MAX_TOOL_CALLS = 3               # per researcher run: the suggested query + up to 2 refinements
MAX_REPEATS = 2                  # repeated calls/results before the researcher must stop searching
RESEARCHER_RECURSION = 12        # LangGraph backstop; the guards end the loop well before this
MAX_REVIEW_ROUNDS = 2            # follow-up rounds per research turn
MAX_FOLLOWUPS_PER_ROUND = 3
MAX_FOLLOWUPS_PER_SOURCE = 2     # per research turn, on top of the first pass
MAX_TOOL_TEXT = 12000            # chars of one tool result kept for the model
MAX_PYTHON_CONTEXT = 12000       # chars of findings given to a Python check
MAX_PYTHON_OUTPUT = 4000         # chars of program output kept
FINDINGS_LIMIT = 12000           # chars per findings section; one limit so reviewer + synthesizer share a prefix
RESEARCH_CACHE_TTL = 600         # s: findings cache, deleted after the synthesizer
CHAT_CACHE_TTL = 3600            # s: conversation-up-to-the-brief cache for follow-up answers


def _turn_list(old, new):
    """List reducer: append within a turn; the planner sends None to reset it for a new research turn."""
    return [] if new is None else (old or []) + new


# ---------- state ----------
class ResearchState(TypedDict, total=False):
    messages: Annotated[list, add_messages]   # whole conversation (reducer appends)
    route: str                                # last decision: "research" or "answer"
    topic: str
    search_plan: dict
    arxiv_findings: str
    local_findings: str
    github_findings: str
    youtube_findings: str
    result_keys: Annotated[list, _turn_list]  # hashes of non-empty raw tool results seen this turn
    followups: Annotated[list, _turn_list]    # executed follow-ups: source, query, key, round, text, result_keys
    pending: list                             # follow-ups approved for the next round
    review_round: int
    review_note: str                          # why the reviewer stopped / what it approved
    brief: str


# ---------- structured outputs ----------
class Route(BaseModel):
    action: Literal["research", "answer"] = Field(
        description="research = new or different topic, or user asks to search again; "
                    "answer = follow-up answerable from the conversation")
    topic: str = Field(default="", description="one-sentence research topic when action is research")


class SearchPlan(BaseModel):
    arxiv: str = Field(description="arXiv query; ti:/abs: prefixes and AND/OR allowed")
    local: str = Field(description="concept description for searching personal notes; keep exact jargon and acronyms")
    github: str = Field(description="GitHub repository query; add language:python and stars:>20 when sensible")
    youtube: str = Field(description="keywords for lecture or explainer videos")


class FollowUp(BaseModel):
    source: Literal["notes", "arxiv", "github", "youtube", "python"]
    query: str = Field(description="a new search query; for python: exactly what to compute or verify")
    reason: str = Field(description="the gap this fills")


class Review(BaseModel):
    done: bool = Field(description="true if the findings are enough for a good study brief")
    reason: str = Field(description="one line")
    followups: list[FollowUp] = Field(default_factory=list, description="at most 3 next steps, only if done is false")


# ---------- router / planner ----------
ROUTER_PROMPT = """You route messages for an ML research assistant.
Choose research for a new topic, a clearly different topic, or an explicit request to search again.
Choose answer for follow-ups about a study brief already in the conversation
(explain a section, compare papers, make a quiz, suggest a study order) and for small talk."""


def router(state: ResearchState) -> dict:
    d = FAST_LLM.with_structured_output(Route).invoke(
        [SystemMessage(ROUTER_PROMPT)] + state["messages"])
    return {"route": d.action, "topic": d.topic}


def planner(state: ResearchState) -> dict:
    plan = FAST_LLM.with_structured_output(SearchPlan).invoke(
        [SystemMessage("Write one search query per source for this ML topic."),
         HumanMessage(f"Topic: {state['topic']}")])
    return {"search_plan": plan.model_dump(),                 # also reset the per-turn loop state
            "result_keys": None, "followups": None, "pending": [], "review_round": 0, "review_note": ""}


# ---------- researchers: guarded model <-> tool loops ----------
class ToolLoopState(MessagesState, total=False):
    task: str              # the instruction (topic + query), reused when tools are taken away
    attempts: list         # [{"call", "result", "args", "outcome", "empty", "text"}]
    repeats: int           # repeated calls / identical results so far
    stop: bool             # no more tool calls: the next model turn must write the report


FINAL_NOTE = ("Searching is over for this run. Write your report from the tool results below only. "
              "If nothing relevant came back, say so in one line and give the reason (e.g. the error).")


def _attempt_history(attempts: list) -> str:
    """Rewritten into the system prompt on every turn, so the model sees what already failed."""
    if not attempts:
        return ""
    lines = "\n".join(f"- {a['args']} -> {a['outcome']}" for a in attempts)
    text = (f"\n\nCalls already made in this run ({len(attempts)}/{MAX_TOOL_CALLS}); don't repeat them, "
            f"a new call must differ in substance:\n{lines}")
    if any(a["empty"] for a in attempts):
        text += ("\nSome calls returned nothing usable. Change approach (broader terms, fewer constraints, "
                 "no field prefixes) or stop and report what you have.")
    return text


def make_researcher(tool, source: str, report: str):
    name = tool.__name__
    llm = RESEARCH_LLM.bind_tools([tool])
    base = (f"You research {source} for an ML engineer. Call {name} with the suggested query; "
            f"refine the query only if results are poor. {report} "
            "Use only what the tool returned and copy URLs exactly. If the tool returns an error, report it.")

    def call_model(state: ToolLoopState) -> dict:
        attempts = state.get("attempts", [])
        if state.get("stop") or len(attempts) >= MAX_TOOL_CALLS:
            # tools taken away; a fresh prompt with the results avoids replaying tool-call history
            results = "\n\n".join(f"{name}({a['args']}) -> {a['outcome']}\n{a['text']}" for a in attempts)
            msg = RESEARCH_LLM.invoke([SystemMessage(f"{base}\n\n{FINAL_NOTE}"),
                                       HumanMessage(f"{state['task']}\n\nTool results:\n{results or '(none)'}")])
            return {"messages": [msg], "stop": True}
        return {"messages": [llm.invoke([SystemMessage(base + _attempt_history(attempts))] + state["messages"])]}

    def run_tools(state: ToolLoopState) -> dict:
        attempts, repeats = list(state.get("attempts", [])), state.get("repeats", 0)
        by_call = {a["call"]: a for a in attempts}
        by_result = {a["result"]: a for a in attempts}
        messages = []
        for tc in state["messages"][-1].tool_calls:
            key = call_key(tc["name"], tc["args"])
            if key in by_call:                                     # cycle: same call (normalised) again
                repeats += 1
                result = {"status": "duplicate",
                          "message": f"Identical to an earlier call ({by_call[key]['outcome']}); not run again."}
            elif len(attempts) >= MAX_TOOL_CALLS:                  # hard cap
                result = {"status": "budget", "message": f"Tool budget of {MAX_TOOL_CALLS} calls used; not run."}
            else:
                try:
                    result = tool(**tc["args"])
                except Exception as e:                             # bad arguments etc.
                    result = {"status": "error", "message": f"{type(e).__name__}: {e}"}
                rkey = digest(result)
                if rkey in by_result:                              # no progress: same output as before
                    repeats += 1
                    if isinstance(result, dict):
                        result = {**result, "note": f"Same result as the earlier call {by_result[rkey]['args']}; "
                                                    "rephrasing again is unlikely to help."}
                text = json.dumps(result, ensure_ascii=False, default=str)[:MAX_TOOL_TEXT]
                a = {"call": key, "result": rkey, "args": tc["args"], "outcome": outcome(result),
                     "empty": is_empty(result), "text": text}
                attempts.append(a)
                by_call[key] = a
                by_result.setdefault(rkey, a)
            messages.append(ToolMessage(json.dumps(result, ensure_ascii=False, default=str)[:MAX_TOOL_TEXT],
                                        tool_call_id=tc["id"], name=tc["name"]))
        stop = repeats >= MAX_REPEATS or len(attempts) >= MAX_TOOL_CALLS
        return {"messages": messages, "attempts": attempts, "repeats": repeats, "stop": stop}

    def after_model(state: ToolLoopState) -> str:
        if state.get("stop"):
            return END
        return "tools" if getattr(state["messages"][-1], "tool_calls", None) else END

    sub = StateGraph(ToolLoopState)
    sub.add_node("model", call_model)
    sub.add_node("tools", run_tools)
    sub.add_edge(START, "model")
    sub.add_conditional_edges("model", after_model, ["tools", END])
    sub.add_edge("tools", "model")
    return sub.compile()


ARXIV = make_researcher(arxiv_search, "arXiv papers",
    "Report the 3-5 most relevant papers: title, first author, year, URL, one line on why it matters.")
NOTES = make_researcher(search_local_notes, "the user's own notes",
    "Leave file_type empty unless the user asked for a specific document type. "
    "Report relevant passages: file name and a 1-2 line summary of each.")
GITHUB = make_researcher(github_search, "GitHub code",
    "Report 3-5 repos: name, URL, stars, and what a learner should read in it.")
YOUTUBE = make_researcher(youtube_search, "YouTube videos",
    "Report 3-5 videos: title, channel, URL, and what each explains.")
SOURCES = {"arxiv": (ARXIV, "arxiv", "arxiv_findings"), "notes": (NOTES, "local", "local_findings"),
           "github": (GITHUB, "github", "github_findings"), "youtube": (YOUTUBE, "youtube", "youtube_findings")}


def run_researcher(agent, topic: str, query: str) -> tuple[str, list]:
    """(report text, hashes of the non-empty raw tool results it saw)."""
    task = f"Topic: {topic}\nSuggested query: {query}"
    try:
        out = agent.invoke({"messages": [HumanMessage(task)], "task": task, "attempts": [], "repeats": 0,
                            "stop": False}, {"recursion_limit": RESEARCHER_RECURSION})
    except Exception as e:                                         # incl. GraphRecursionError (backstop)
        return f"(no results: {e})", []
    return text_of(out["messages"][-1]), [a["result"] for a in out.get("attempts", []) if not a["empty"]]


def researcher_node(source: str):
    agent, plan_key, out_key = SOURCES[source]

    def node(state: ResearchState) -> dict:
        text, keys = run_researcher(agent, state["topic"], state["search_plan"][plan_key])
        return {out_key: text, "result_keys": keys}
    return node


# ---------- Python checks (hosted sandbox) ----------
CODE_LLM = gemini(MODEL, thinkin_level="low").bind_tools([{"code_execution": {}}])
PYTHON_PROMPT = """You check one claim or compute one value for an ML study brief by writing and running Python.
Use only the task and the context given. Keep the code short and deterministic (numpy and sympy are available).
End with one line starting 'Result:' that states what the computation showed."""


def python_check(task: str, context: str) -> tuple[str, list]:
    """Runs model-written code in Gemini's code-execution sandbox (no network, no access to this machine).
    Nothing is executed locally; only the task and the findings text are sent."""
    try:
        reply = CODE_LLM.invoke([SystemMessage(PYTHON_PROMPT),
                                 HumanMessage(f"Task: {task}\n\nContext:\n{context[:MAX_PYTHON_CONTEXT]}")])
    except Exception as e:
        return f"(no results: python check failed: {type(e).__name__}: {e})", []
    code, output, prose = [], [], []
    for block in reply.content if isinstance(reply.content, list) else [reply.content]:
        if isinstance(block, str):
            prose.append(block)
        elif block.get("type") == "executable_code":
            code.append(block.get("executable_code", ""))
        elif block.get("type") == "code_execution_result":
            output.append(block.get("code_execution_result", ""))
        elif block.get("type") == "text":
            prose.append(block.get("text", ""))
    code_text, out_text = "\n\n".join(code), "\n".join(output)[:MAX_PYTHON_OUTPUT]
    if not code_text:
        return f"(no results: no code was run for: {task})", []
    text = (f"Task: {task}\n```python\n{code_text}\n```\nOutput:\n```\n{out_text}\n```\n"
            f"{''.join(prose).strip()}")
    return text, [digest([code_text, out_text])]


# ---------- reviewer + follow-ups (guarded cycle) ----------
REVIEW_PROMPT = """You review research findings before a study brief is written for an ML engineer.
Decide whether a few targeted extra steps would clearly improve the brief. Good reasons:
- other sources name a concept, method or term that the notes search didn't look for -> search notes for it;
- an important sub-topic has no paper, repo or video -> search that source with a focused query;
- a formula, derivation step or number in the findings can be checked by computation -> python
  (state exactly what to compute, with the values).
Never repeat anything under ALREADY DONE (the same query in other words is a repeat).
Prefer done=true when the findings are adequate: every follow-up costs time."""


def _first_pass_keys(plan: dict) -> set:
    return {action_key(src, plan[plan_key]) for src, (_, plan_key, _) in SOURCES.items() if plan.get(plan_key)}


def approve_followups(proposed: list, plan: dict, log: list, next_round: int) -> tuple[list, str]:
    """Deterministic guard over the reviewer's proposals: per-round and per-source caps + cycle detection."""
    done = _first_pass_keys(plan) | {e["key"] for e in log}
    per_source = Counter(e["source"] for e in log)
    approved, dropped = [], []
    for f in proposed:
        key = action_key(f.source, f.query)
        if len(approved) >= MAX_FOLLOWUPS_PER_ROUND:
            dropped.append(f"{f.source}: round limit")
        elif key in done:
            dropped.append(f"{f.source}: repeat of an earlier query")
        elif per_source[f.source] >= MAX_FOLLOWUPS_PER_SOURCE:
            dropped.append(f"{f.source}: source limit")
        else:
            done.add(key)
            per_source[f.source] += 1
            approved.append({"source": f.source, "query": f.query, "reason": f.reason, "key": key,
                             "round": next_round})
    note = f"round {next_round}: {len(approved)} follow-up(s)" + (f", dropped {dropped}" if dropped else "")
    return approved, note


def _stop_reason(state: ResearchState, rnd: int, log: list) -> str:
    """Hard cap + progress check: the last round must have produced raw results not seen before."""
    if rnd >= MAX_REVIEW_ROUNDS:
        return f"stopped: round limit ({MAX_REVIEW_ROUNDS}) reached"
    if rnd > 0:
        seen = set(state.get("result_keys") or []) | {k for e in log if e["round"] < rnd for k in e["result_keys"]}
        fresh = {k for e in log if e["round"] == rnd for k in e["result_keys"]} - seen
        if not fresh:
            return f"stopped: round {rnd} brought no new results"
    return ""


def _first_pass(state: ResearchState) -> str:
    """The 4 researchers' findings: fixed for the rest of the turn, so it is the cached prefix."""
    parts = [f"TOPIC: {state['topic']}"]
    parts += [f"{label}:\n{(state.get(key) or '')[:FINDINGS_LIMIT]}" for label, key in
              (("PAPERS", "arxiv_findings"), ("MY NOTES", "local_findings"),
               ("CODE", "github_findings"), ("VIDEOS", "youtube_findings"))]
    return "\n\n".join(parts)


def _followups_text(state: ResearchState) -> str:
    return "\n\n".join(f"FOLLOW-UP [{e['source']}] {e['query']}:\n{e['text'][:FINDINGS_LIMIT]}"
                       for e in state.get("followups") or [])


def _findings(state: ResearchState) -> str:
    return "\n\n".join(p for p in (_first_pass(state), _followups_text(state)) if p)


# reviewer + synthesizer share this system prompt and the first-pass findings (one explicit cache per turn);
# their own instructions and the follow-ups go after the cached prefix
BRIEF_SYSTEM = ("You work on research findings for an ML engineer who learns bottom-up. The findings come first; "
                "follow the TASK given after them. Use only the findings; never invent papers, links, repos or videos.")


def _research_call(state: ResearchState, llm, task: str, schema=None):
    prefix = [HumanMessage(_first_pass(state))]
    tail = "\n\n".join(p for p in (_followups_text(state), f"TASK:\n{task}") if p)
    key = cache.key_for("research", BRIEF_SYSTEM, prefix)
    return cache.invoke(llm, BRIEF_SYSTEM, prefix, [HumanMessage(tail)], key, RESEARCH_CACHE_TTL, schema), key


def reviewer(state: ResearchState) -> dict:
    rnd, log = state.get("review_round", 0), state.get("followups") or []
    if reason := _stop_reason(state, rnd, log):
        return {"pending": [], "review_note": reason}
    plan = state["search_plan"]
    already = [f"- [{src}] {plan[k]}" for src, (_, k, _) in SOURCES.items() if plan.get(k)]
    already += [f"- [{e['source']}] {e['query']}" for e in log]
    used = Counter(e["source"] for e in log)
    budget = ", ".join(f"{s} {MAX_FOLLOWUPS_PER_SOURCE - used[s]}" for s in (*SOURCES, "python"))
    review, _ = _research_call(state, FAST_LLM, f"{REVIEW_PROMPT}\n\nALREADY DONE:\n" + "\n".join(already)
                               + f"\n\nFollow-ups left per source: {budget}. Round {rnd + 1} of {MAX_REVIEW_ROUNDS}.",
                               schema=Review)
    if review is None or review.done or not review.followups:
        return {"pending": [], "review_note": f"done: {review.reason if review else 'no review'}"}
    approved, note = approve_followups(review.followups, plan, log, rnd + 1)
    if not approved:
        return {"pending": [], "review_note": f"stopped: nothing new to do ({note})"}
    return {"pending": approved, "review_round": rnd + 1, "review_note": note}


def after_review(state: ResearchState):
    if not state.get("pending"):
        return "synthesizer"
    context = _findings(state)
    return [Send("followup", {**f, "topic": state["topic"], "context": context}) for f in state["pending"]]


def followup(task: dict) -> dict:
    if task["source"] == "python":
        text, keys = python_check(task["query"], task["context"])
    else:
        text, keys = run_researcher(SOURCES[task["source"]][0], task["topic"], task["query"])
    entry = {k: task[k] for k in ("source", "query", "reason", "key", "round")}
    return {"followups": [{**entry, "text": text, "result_keys": keys}]}


# ---------- synthesizer / answer ----------
SYNTH_PROMPT = """Write a study brief for an ML engineer who learns bottom-up.
Use ONLY the findings provided. Never invent papers, links, repos or videos; copy URLs exactly.
Use exactly these markdown headings, in this order:
## Core idea
## What my notes cover
## Papers
## Repos
## Videos
## Self-test
Core idea builds from prerequisites upward in 15-20 sentences. What my notes cover says what the
user's notes already explain and what is missing. Papers gives a reading order with one reason
each. Repos says what to look at in each. Videos goes shortest path first. Self-test has three questions.
FOLLOW-UP entries are targeted extra searches: merge them into the matching sections. If any FOLLOW-UP is a
python check, add a final '## Checks' section with what was computed and the result, and point out in
Core idea if a check contradicts a source."""


def synthesizer(state: ResearchState) -> dict:
    reply, key = _research_call(state, MAIN_LLM, SYNTH_PROMPT)
    cache.drop(key)                                  # last use of this turn's findings cache
    brief = text_of(reply)
    return {"brief": brief, "messages": [AIMessage(content=brief)]}


ANSWER_PROMPT = """You are an ML research assistant for an engineer who learns bottom-up.
Answer using the study briefs and messages in this conversation. If the answer needs sources
that are not in the conversation, say so and suggest researching it."""


def answer(state: ResearchState) -> dict:
    """The conversation up to the latest brief is cached once and reused by every follow-up until the next
    research turn; only the questions and answers after it are sent each time."""
    messages, brief = state["messages"], state.get("brief")
    cut = max((i for i, m in enumerate(messages) if brief and isinstance(m, AIMessage) and text_of(m) == brief),
              default=-1)
    prefix, tail = messages[:cut + 1], messages[cut + 1:]
    reply = cache.invoke(MAIN_LLM, ANSWER_PROMPT, prefix, tail,
                         cache.key_for("chat", ANSWER_PROMPT, prefix), CHAT_CACHE_TTL)
    return {"messages": [AIMessage(content=text_of(reply))]}


# ---------- graph ----------
RESEARCHERS = [f"{s}_researcher" for s in SOURCES]


def build_graph(checkpointer=None):
    g = StateGraph(ResearchState)
    g.add_node("router", router)
    g.add_node("planner", planner)
    for source in SOURCES:
        g.add_node(f"{source}_researcher", researcher_node(source))
    g.add_node("reviewer", reviewer)
    g.add_node("followup", followup)
    g.add_node("synthesizer", synthesizer)
    g.add_node("answer", answer)

    g.add_edge(START, "router")
    g.add_conditional_edges("router", lambda s: s["route"],
                            {"research": "planner", "answer": "answer"})
    for r in RESEARCHERS:
        g.add_edge("planner", r)                  # fan-out: 4 branches run in parallel
    g.add_edge(RESEARCHERS, "reviewer")           # waiting edge: fan-in after all 4
    g.add_conditional_edges("reviewer", after_review, ["followup", "synthesizer"])
    g.add_edge("followup", "reviewer")            # runs after every follow-up of the round has finished
    g.add_edge("synthesizer", END)
    g.add_edge("answer", END)
    return g.compile(checkpointer=checkpointer)
