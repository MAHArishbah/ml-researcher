def _turn_list(old, new):
    """List reducer: append within a turn; the planner sends None to reset it for a new research turn."""
    return [] if new is None else (old or []) + new


# ---------- state ----------
class ResearchState(TypedDict, total=False):
    messages: Annotated[list, add_messages]   # whole conversation (reducer appends)
    route: str                                # last decision: "research" or "answer"
    topic: str
    search_plan: dict
    arxiv_findings: str
    local_findings: str
    github_findings: str
    youtube_findings: str
    code_findings: str                        # the user's own code (code index)
    result_keys: Annotated[list, _turn_list]  # hashes of non-empty raw tool results seen this turn
    allowed_urls: Annotated[list, _turn_list] # URLs tools returned this turn: the only links a brief may contain
    tool_calls: Annotated[list, _turn_list]   # name of every tool actually run this turn (searches, python, web)
    followups: Annotated[list, _turn_list]    # executed follow-ups: source, query, key, round, text, result_keys
    pending: list                             # follow-ups approved for the next round
    review_round: int
    review_note: str                          # why the reviewer stopped / what it approved
    brief: str
    history_summary: str                      # summary of messages[:summary_upto] (long conversations only)
    summary_upto: int
    web: bool                                 # this turn asked for web search (message started with /web)
    web_findings: str                         # verified web sources (arXiv-API metadata + bare links)
    read_url: str                             # this turn's /read URL ("" if none)
    page_url: str                             # where that URL finally landed (after safe redirects)
    page_findings: str                        # the article's text (untrusted data), or why it couldn't be read


# ---------- structured outputs ----------
class Route(BaseModel):
    action: Literal["research", "answer"] = Field(
        description="research = new or different topic, or user asks to search again; "
                    "answer = follow-up answerable from the conversation")
    topic: str = Field(default="", description="one-sentence research topic when action is research")


class SearchPlan(BaseModel):
    arxiv: str = Field(description="arXiv query; ti:/abs: prefixes and AND/OR allowed")
    local: str = Field(description="concept description for searching personal notes; keep exact jargon and acronyms")
    github: str = Field(description="GitHub repository query; add language:python and stars:>20 when sensible")
    youtube: str = Field(description="keywords for lecture or explainer videos")
    code: str = Field(description="what the user's own code would contain for this topic: function names, libraries and ML terms")


class FollowUp(BaseModel):
    source: Literal["notes", "code", "arxiv", "github", "youtube", "python"]
    query: str = Field(description="a new search query; for python: exactly what to compute or verify")
    reason: str = Field(description="the gap this fills")


class Review(BaseModel):
    done: bool = Field(description="true if the findings are enough for a good study brief")
    reason: str = Field(description="one line")
    followups: list[FollowUp] = Field(default_factory=list, description="at most 3 next steps, only if done is false")


# ---------- router / planner ----------
# deterministic backstop for the rule above: a message that points at the user's own material always searches
_POINTS_AT_OWN = re.compile(r"\b(?:in|from|check|search|see|look\s+(?:in|at)|per)\s+(?:my\s+|the\s+)?(?:own\s+)?"
                            r"(?:notes?|code|notebooks?|repos?|projects?)\b|\bmy\s+(?:own\s+)?(?:notes?|code|notebooks?)\b",
                            re.IGNORECASE)


def _request(state) -> str:
    """The user's latest message, word for word: the planner, reviewer and brief writer need every part of it
    (the router's topic is only a short summary)."""
    return next((text_of(m) for m in reversed(state["messages"]) if isinstance(m, HumanMessage)), "")


def _recent(messages: list, n: int) -> list:
    """The last n messages, starting at a user message (a model reply can't open a conversation)."""
    tail = messages[-n:]
    while tail and not isinstance(tail[0], HumanMessage):
        tail = tail[1:]
    return tail


def router(state: ResearchState) -> dict:
    """Only needs the latest exchange to classify the new message; the whole history would just cost tokens.
    Fails soft: if the routing call gets no answer (Google stalled or busy), the route is decided in code
    instead of failing the turn: commands or own material -> research; an earlier brief -> answer; else research."""
    message = text_of(state["messages"][-1])
    web = bool(re.search(r"(?<!\S)/web(?!\S)", message, re.IGNORECASE))   # the /web command, anywhere; opt-in only
    read = urlreader.parse_read(message)                        # "/read <url> question": explicit opt-in only
    own = bool(_POINTS_AT_OWN.search(message))                  # "it's in my notes" -> must search them
    try:
        d = structured(FAST_LLM, Route).invoke(
            [SystemMessage(prompt("ROUTER", topic=state.get("topic") or "none yet"))]
            + _recent(state["messages"], ROUTER_HISTORY))
        action, topic = d.action, d.topic
    except Exception as e:                                       # only chooses a route: nothing the user reads
        action = "research" if (web or read or own) else ("answer" if state.get("brief") else "research")
        topic = ""
        log.warning("router failed, routed in code to %s: %s", action, e, extra={"json_fields": {
            "event": "router_fallback", "route": action, "error": f"{type(e).__name__}: {str(e)[:200]}"}})
        _notice(f"Routing call failed; continuing with {action}")
    return {"route": "research" if (web or read or own) else action, "topic": topic or message[:200], "web": web,
            "read_url": read[0] if read else ""}


def web_researcher(state: ResearchState) -> dict:
    """Runs beside the 4 researchers but does nothing unless this turn's message started with /web."""
    if not state.get("web"):
        return {"web_findings": ""}
    if not websearch.available():
        return {"web_findings": "(no results: web search is off - needs a google_genai MAIN_MODEL and WEB_SEARCH=true)"}
    try:
        text, urls, _ = websearch.search(state["topic"])
    except Exception as e:
        return {"web_findings": f"(no results: web search failed: {type(e).__name__}: {e})"}
    _flag("web result", text)
    return {"web_findings": text, "allowed_urls": urls, "tool_calls": ["web_search"]}


