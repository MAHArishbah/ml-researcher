def run_researcher(agent, topic: str, query: str) -> tuple[str, list, list, list]:
    """(report text, hashes of the non-empty raw tool results it saw, URLs those results contained,
    names of the tools it actually ran)."""
    task = f"Topic: {topic}\nSuggested query: {query}"
    try:
        out = agent.invoke({"messages": [HumanMessage(task)], "task": task, "attempts": [], "repeats": 0,
                            "stop": False}, {"recursion_limit": RESEARCHER_RECURSION})
    except Exception as e:                                         # incl. GraphRecursionError (backstop)
        return f"(no results: {e})", [], [], []
    attempts = out.get("attempts", [])
    return (text_of(out["messages"][-1]), [a["result"] for a in attempts if not a["empty"]],
            [u for a in attempts for u in a.get("urls", [])], [a["tool"] for a in attempts])


def researcher_node(source: str):
    agent, plan_key, out_key = SOURCES[source]

    def node(state: ResearchState) -> dict:
        text, keys, urls, calls = run_researcher(agent, state["topic"], state["search_plan"][plan_key])
        return {out_key: text, "result_keys": keys, "allowed_urls": urls, "tool_calls": calls}
    return node


# ---------- Python checks (hosted sandbox) ----------
SANDBOX = get_sandbox()                      # None -> Python checks disabled (reviewer can't propose them)
PYTHON_PROMPT = prompt("PYTHON_CHECK")


def python_check(task: str, context: str) -> tuple[str, list]:
    """Runs model-written code in the provider's hosted sandbox (no network, no access to this machine).
    Nothing is executed locally; only the task and the findings text are sent."""
    if SANDBOX is None:
        return "(no results: python checks are disabled, CODE_SANDBOX=none)", []
    try:
        run = SANDBOX.run(PYTHON_PROMPT, f"Task: {task}\n\nContext:\n{context[:MAX_PYTHON_CONTEXT]}")
    except Exception as e:
        return f"(no results: python check failed: {type(e).__name__}: {e})", []
    if not run.code:
        return f"(no results: no code was run for: {task})", []
    out_text = run.output[:MAX_PYTHON_OUTPUT]
    _flag("python output", out_text)
    text = f"Task: {task}\n```python\n{run.code}\n```\nOutput:\n```\n{out_text}\n```\n{run.prose.strip()}"
    return text, [digest([run.code, out_text])]


