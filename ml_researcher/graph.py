REVIEW_PROMPT = prompt("REVIEW")


def _first_pass_keys(plan: dict) -> set:
    return {action_key(src, plan[plan_key]) for src, (_, plan_key, _) in SOURCES.items() if plan.get(plan_key)}


def approve_followups(proposed: list, plan: dict, log: list, next_round: int) -> tuple[list, str]:
    """Deterministic guard over the reviewer's proposals: per-round and per-source caps + cycle detection."""
    done = _first_pass_keys(plan) | {e["key"] for e in log}
    per_source = Counter(e["source"] for e in log)
    approved, dropped = [], []
    for f in proposed:
        key = action_key(f.source, f.query)
        if len(approved) >= MAX_FOLLOWUPS_PER_ROUND:
            dropped.append(f"{f.source}: round limit")
        elif f.source == "python" and SANDBOX is None:
            dropped.append("python: no sandbox configured")
        elif key in done:
            dropped.append(f"{f.source}: repeat of an earlier query")
        elif per_source[f.source] >= MAX_FOLLOWUPS_PER_SOURCE:
            dropped.append(f"{f.source}: source limit")
        else:
            done.add(key)
            per_source[f.source] += 1
            approved.append({"source": f.source, "query": f.query, "reason": f.reason, "key": key,
                             "round": next_round})
    note = f"round {next_round}: {len(approved)} follow-up(s)" + (f", dropped {dropped}" if dropped else "")
    return approved, note


def _stop_reason(state: ResearchState, rnd: int, log: list) -> str:
    """Hard cap + progress check: the last round must have produced raw results not seen before."""
    if rnd >= MAX_REVIEW_ROUNDS:
        return f"stopped: round limit ({MAX_REVIEW_ROUNDS}) reached"
    if rnd > 0:
        seen = set(state.get("result_keys") or []) | {k for e in log if e["round"] < rnd for k in e["result_keys"]}
        fresh = {k for e in log if e["round"] == rnd for k in e["result_keys"]} - seen
        if not fresh:
            return f"stopped: round {rnd} brought no new results"
    return ""


def _first_pass(state: ResearchState) -> str:
    """The 5 researchers' findings: fixed for the rest of the turn, so it is the cached prefix."""
    parts = [f"TOPIC: {state['topic']}", f"USER'S REQUEST (answer every part of it):\n{_request(state)}"]
    parts += [f"{label}:\n<findings>\n{(state.get(key) or '')[:FINDINGS_LIMIT]}\n</findings>" for label, key in
              (("PAPERS", "arxiv_findings"), ("MY NOTES", "local_findings"), ("MY CODE", "code_findings"),
               ("GITHUB REPOS", "github_findings"), ("VIDEOS", "youtube_findings"))]
    if state.get("page_findings"):                   # only on /read turns
        parts.insert(1, f"SHARED ARTICLE:\n<findings>\n{state['page_findings']}\n</findings>")
    if state.get("web_findings"):                    # only on /web turns
        parts.append(f"NEW ON THE WEB (arXiv-verified):\n<findings>\n{state['web_findings'][:FINDINGS_LIMIT]}\n</findings>")
    return "\n\n".join(parts)


def _followups_text(state: ResearchState) -> str:
    return "\n\n".join(f"FOLLOW-UP [{e['source']}] {e['query']}:\n<findings>\n{e['text'][:FINDINGS_LIMIT]}\n</findings>"
                       for e in state.get("followups") or [])


def _findings(state: ResearchState) -> str:
    return "\n\n".join(p for p in (_first_pass(state), _followups_text(state)) if p)


# reviewer + synthesizer share this system prompt and the first-pass findings (one explicit cache per turn);
# their own instructions and the follow-ups go after the cached prefix
BRIEF_SYSTEM = prompt("BRIEF_SYSTEM")


def _research_call(state: ResearchState, llm, task: str, schema=None):
    prefix = [HumanMessage(_first_pass(state))]
    tail = "\n\n".join(p for p in (_followups_text(state), f"TASK:\n{task}") if p)
    key = cache.key_for("research", BRIEF_SYSTEM, prefix)
    return cache.invoke(llm, BRIEF_SYSTEM, prefix, [HumanMessage(tail)], key, RESEARCH_CACHE_TTL, schema), key


def reviewer(state: ResearchState) -> dict:
    rnd, done_log = state.get("review_round", 0), state.get("followups") or []
    if reason := _stop_reason(state, rnd, done_log):
        return {"pending": [], "review_note": reason}
    plan = state["search_plan"]
    already = [f"- [{src}] {plan[k]}" for src, (_, k, _) in SOURCES.items() if plan.get(k)]
    already += [f"- [{e['source']}] {e['query']}" for e in done_log]
    used = Counter(e["source"] for e in done_log)
    sources = (*SOURCES, "python") if SANDBOX else tuple(SOURCES)
    budget = ", ".join(f"{s} {MAX_FOLLOWUPS_PER_SOURCE - used[s]}" for s in sources)
    try:      # LONG_LLM: same model and effort as FAST_LLM, 90 s limit (one non-streamed call over all findings)
        review, _ = _research_call(state, LONG_LLM, f"{REVIEW_PROMPT}\n\nALREADY DONE:\n" + "\n".join(already)
                                   + f"\n\nFollow-ups left per source: {budget}. Round {rnd + 1} of {MAX_REVIEW_ROUNDS}.",
                                   schema=Review)
    except Exception as e:    # the review is optional: write the brief from what we have instead of failing the turn
        log.warning("review skipped: %s", e, extra={"json_fields": {
            "event": "review_skipped", "round": rnd + 1, "error": f"{type(e).__name__}: {str(e)[:200]}"}})
        return {"pending": [], "review_note": f"stopped: review failed ({type(e).__name__}), brief written from findings"}
    if review is None or review.done or not review.followups:
        return {"pending": [], "review_note": f"done: {review.reason if review else 'no review'}"}
    approved, note = approve_followups(review.followups, plan, done_log, rnd + 1)
    if not approved:
        return {"pending": [], "review_note": f"stopped: nothing new to do ({note})"}
    return {"pending": approved, "review_round": rnd + 1, "review_note": note}


def after_review(state: ResearchState):
    if not state.get("pending"):
        return "synthesizer"
    context = _findings(state)
    return [Send("followup", {**f, "topic": state["topic"], "context": context}) for f in state["pending"]]


def followup(task: dict) -> dict:
    if task["source"] == "python":
        (text, keys), urls, calls = python_check(task["query"], task["context"]), [], ["python_check"]
    else:
        text, keys, urls, calls = run_researcher(SOURCES[task["source"]][0], task["topic"], task["query"])
    entry = {k: task[k] for k in ("source", "query", "reason", "key", "round")}
    return {"followups": [{**entry, "text": text, "result_keys": keys}], "allowed_urls": urls, "tool_calls": calls}


# ---------- synthesizer / answer ----------
BUSY_WAITS = (10, 30)            # s: extra back-off when the provider is out of capacity (429), before giving up


def _is_busy(e: Exception) -> bool:
    """Provider out of capacity: a rate-limit error after the SDK's own quick retries (any provider)."""
    code = getattr(e, "code", None) or getattr(e, "status_code", None)
    return isinstance(e, ModelRateLimitError) or code == 429 or "RESOURCE_EXHAUSTED" in str(e)


def _notice(message: str) -> None:
    """Show a status line in the UI / terminal (LangGraph custom stream); no-op outside a streamed run."""
    try:
        get_stream_writer()({"notice": message})
    except Exception:
        pass


def _busy_retry(step: str, call):
    """Run the call; on a 429, wait BUSY_WAITS[0], retry the SAME model, then BUSY_WAITS[1], then give up.
    Google's own retries come 1-3 s apart and usually land in the same busy period; this waits it out.
    Only for steps whose output the user reads (synthesizer, answer): a slower turn instead of a failed one."""
    for wait in (*BUSY_WAITS, None):
        try:
            return call()
        except Exception as e:
            if wait is None or not _is_busy(e):
                raise
            log.warning("%s: provider busy (429), retrying in %d s", step, wait, extra={"json_fields": {
                "event": "model_backoff", "step": step, "wait_s": wait, "error": str(e)[:200]}})
            _notice(f"Google is busy, retrying in {wait} s\u2026")
            time.sleep(wait)


SYNTH_PROMPT = prompt("SYNTH")


def synthesizer(state: ResearchState) -> dict:
    reply, key = _busy_retry("synthesizer", lambda: _research_call(state, MAIN_LLM, SYNTH_PROMPT))
    cache.drop(key)                                  # last use of this turn's findings cache
    allowed = (state.get("allowed_urls") or []) + ([state["page_url"]] if state.get("page_url") else [])
    brief = _only_known_links(text_of(reply), allowed, "synthesizer")
    return {"brief": brief, "messages": [AIMessage(content=brief)]}


def _only_known_links(text: str, allowed: list, node: str) -> str:
    """Strip every link that no tool returned (planted by injected text, or invented by the model)."""
    text, removed = filter_urls(text, allowed)
    if removed:
        log.warning("removed %d unverified link(s) from %s", len(removed), node, extra={"json_fields": {
            "event": "url_removed", "node": node, "count": len(removed), "urls": removed[:5]}})
    return text


ANSWER_PROMPT = prompt("ANSWER")


SUMMARY_PROMPT = prompt("SUMMARY")


def _tokens(messages: list) -> int:
    return sum(len(text_of(m)) for m in messages) // 4          # ~4 characters per token


def _keep_from(messages: list, brief: str | None) -> int:
    """Start of the part kept word for word: the last KEEP_TURNS completed turns and the latest brief
    (with the question that produced it), whichever starts earlier."""
    users = [i for i, m in enumerate(messages) if isinstance(m, HumanMessage)]
    start = users[-(KEEP_TURNS + 1)] if len(users) > KEEP_TURNS else 0      # +1: the current, unanswered question
    briefs = [i for i, m in enumerate(messages) if brief and isinstance(m, AIMessage) and text_of(m) == brief]
    if briefs:
        asked = max((i for i in users if i < briefs[-1]), default=0)
        start = min(start, asked)
    return start


def _summarise(previous: str | None, messages: list) -> str:
    convo = "\n\n".join(f"{'USER' if isinstance(m, HumanMessage) else 'ASSISTANT'}: {text_of(m)}" for m in messages)
    head = f"PREVIOUS SUMMARY:\n{previous}\n\nNEW MESSAGES:\n" if previous else ""
    return text_of(LONG_LLM.invoke([SystemMessage(SUMMARY_PROMPT), HumanMessage(head + convo)]))


def answer(state: ResearchState) -> dict:
    """Follow-up answers from the conversation.
    Short conversation: sent whole. Past SUMMARY_TRIGGER_TOKENS: the older turns are replaced by a summary
    (kept in the state and only extended when more turns age out), while the latest brief and the last
    KEEP_TURNS turns stay word for word. The part up to the latest brief is cached for the next follow-ups."""
    messages, brief = state["messages"], state.get("brief")
    system, update = ANSWER_PROMPT, {}
    start = _keep_from(messages, brief)
    if start > 0 and _tokens(messages) > SUMMARY_TRIGGER_TOKENS:
        summary, upto = state.get("history_summary"), state.get("summary_upto", 0)
        if upto < start:                                     # more turns aged out since the last summary
            summary = _summarise(summary, messages[upto:start])
            update = {"history_summary": summary, "summary_upto": start}
            log.info("history summarised", extra={"json_fields": {
                "event": "history_summary", "messages_summarised": start, "tokens_before": _tokens(messages),
                "tokens_after": _tokens(messages[start:]) + len(summary) // 4}})
        system = f"{ANSWER_PROMPT}\n\nSUMMARY OF THE EARLIER CONVERSATION:\n{summary}"
        messages = messages[start:]
    cut = max((i for i, m in enumerate(messages) if brief and isinstance(m, AIMessage) and text_of(m) == brief),
              default=-1)
    prefix, tail = messages[:cut + 1], messages[cut + 1:]
    reply = _busy_retry("answer", lambda: cache.invoke(MAIN_LLM, system, prefix, tail,
                                                          cache.key_for("chat", system, prefix), CHAT_CACHE_TTL))
    # follow-up answers may only reuse links already in the conversation (briefs were filtered when written)
    seen = [u for m in state["messages"] for u in find_urls(text_of(m))]   # not the summary: model-written
    return {"messages": [AIMessage(content=_only_known_links(text_of(reply), seen, "answer"))], **update}


# ---------- graph ----------
RESEARCHERS = [f"{s}_researcher" for s in SOURCES]


def build_graph(checkpointer=None):
    g = StateGraph(ResearchState)
    g.add_node("router", router)
    g.add_node("planner", planner)
    for source in SOURCES:
        g.add_node(f"{source}_researcher", researcher_node(source))
    g.add_node("web_researcher", web_researcher)        # no-op unless the message starts with /web
    g.add_node("reviewer", reviewer)
    g.add_node("followup", followup)
    g.add_node("synthesizer", synthesizer)
    g.add_node("answer", answer)

    g.add_edge(START, "router")
    g.add_conditional_edges("router", lambda s: s["route"],
                            {"research": "planner", "answer": "answer"})
    for r in RESEARCHERS:
        g.add_edge("planner", r)                  # fan-out: 4 branches run in parallel
    g.add_edge("planner", "web_researcher")
    g.add_edge([*RESEARCHERS, "web_researcher"], "reviewer")   # waiting edge: fan-in after all of them
    g.add_conditional_edges("reviewer", after_review, ["followup", "synthesizer"])
    g.add_edge("followup", "reviewer")            # runs after every follow-up of the round has finished
    g.add_edge("synthesizer", END)
    g.add_edge("answer", END)
    return g.compile(checkpointer=checkpointer)
